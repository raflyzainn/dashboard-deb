// Jalankan lewat tool browser pada draf campus-011, RAB 01_RAB_10_Unit.xlsx.
async page => {
 const assert=(ok,message)=>{if(!ok)throw Error(message);};
 await page.setViewportSize({width:1440,height:1000});
 await page.goto('http://127.0.0.1:5182/campus/pencairan?bagian=rab&butir=rab&rabStep=term1');
 const summary=page.locator('[aria-label="Ringkasan pembagian RAB"]');
 const cards=page.locator('[aria-label="Pembagian jumlah item RAB"] article');
 const next=page.getByRole('button',{name:'Lanjut',exact:true});
 const quantities=page.getByRole('spinbutton');
 await quantities.first().waitFor();
 assert(await cards.count()===4,'Pembagian kampus harus memakai kartu');
 assert(await quantities.count()===4,'Harus ada input per item pada kartu');
 await quantities.first().fill('1.5');assert(await next.isDisabled(),'Pecahan harus ditolak');
 for(let i=0;i<4;i++)await quantities.nth(i).fill('10');
 assert(await next.isDisabled(),'Batas 70% harus berlaku');
 for(let i=0;i<4;i++)await quantities.nth(i).fill('3');
 await next.click();await page.waitForURL('**rabStep=term2');
 assert(await quantities.count()===0,'Termin 2 hanya membaca sisa');
 assert((await summary.innerText()).includes('Rp6.000.000'),'Nominal tersimpan harus tampil');
 await page.getByRole('button',{name:'Kembali',exact:true}).click();await quantities.first().waitFor();
 assert(await quantities.first().inputValue()==='3','Kembali harus memuat pembagian tersimpan');
 await quantities.first().fill('4');
 await page.getByRole('button',{name:'2. Periksa RAB 100%',exact:true}).click();
 await page.getByRole('button',{name:'Tetap di sini',exact:true}).click();
 assert(await quantities.first().inputValue()==='4','Batal navigasi harus mempertahankan input');
 await next.click();await page.waitForURL('**rabStep=term2');
 assert((await summary.innerText()).includes('Rp7.000.000'),'Lanjut harus menyimpan perubahan');
 await page.getByRole('button',{name:'3. Atur Termin 1',exact:true}).click();
 await quantities.first().fill('3');await next.click();await page.waitForURL('**rabStep=term2');
 await page.reload();await summary.waitFor();
 assert((await summary.innerText()).includes('Rp6.000.000'),'Pembagian harus bertahan setelah reload');
 await page.getByRole('button',{name:'2. Periksa RAB 100%',exact:true}).click();
 await page.getByRole('button',{name:'Kembali',exact:true}).click();
 await page.getByLabel('Unggah Excel RAB 100%',{exact:true}).waitFor();
 await next.click();await page.waitForURL('**rabStep=full');
 await next.click();await quantities.first().waitFor();
 assert(await quantities.first().inputValue()==='3','Navigasi upload tidak boleh menghapus draf');
 await next.click();await page.waitForURL('**rabStep=term2');
 await page.locator('[aria-label="Perbandingan tiga RAB"]').scrollIntoViewIfNeeded();await page.screenshot({path:'.playwright-mcp/campus-rab-term2-cards.png'});
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Halaman tidak boleh melebar');
 await page.setViewportSize({width:1440,height:1000});
 return {cards:true,integerAndLimitValidation:true,backAndForward:true,draftPreserved:true,mobile:true};
}
